"""Embed index.html into page.py so the Vercel function always has it (run before each deploy)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
html = open(os.path.join(HERE, "index.html"), encoding="utf-8").read()
open(os.path.join(HERE, "page.py"), "w", encoding="utf-8").write("# Generated by build_page.py from index.html. Edit index.html, not this file.\nHTML = " + repr(html) + "\n")
print("page.py", len(html), "chars")
